const bookList = document.getElementById("bookList");
const search = document.getElementById("search");
const reader = document.getElementById("reader");

let category = "Semua";
let saved = JSON.parse(localStorage.getItem("rasyaSaved") || "[]");
let currentId = null;
let showingSaved = false;

function renderBooks() {
  const keyword = search.value.toLowerCase();

  const filtered = stories.filter(story => {
    const matchCategory =
      category === "Semua" || story.category === category;

    const matchSearch =
      story.title.toLowerCase().includes(keyword) ||
      story.desc.toLowerCase().includes(keyword);

    const matchSaved =
      !showingSaved || saved.includes(story.id);

    return matchCategory && matchSearch && matchSaved;
  });

  bookList.innerHTML = filtered.map(story => `
    <div class="book-card" data-id="${story.id}">
      <div class="cover" style="background:${story.color}">
        <span class="number">RASYA'S STORYBOOK</span>
        <h3>${story.title}</h3>
        <small>${story.category.toUpperCase()}</small>
      </div>

      <div class="card-info">
        <span>${story.category}</span>
        <h3>${story.title}</h3>
        <p>${story.desc}</p>

        <div class="card-actions">
          <span class="read">BACA CERITA ↗</span>
          <button class="heart" data-save="${story.id}">
            ${saved.includes(story.id) ? "♥" : "♡"}
          </button>
        </div>
      </div>
    </div>
  `).join("");

  document.getElementById("total").textContent =
    String(filtered.length).padStart(2, "0") + " STORIES";

  document.getElementById("empty").hidden =
    filtered.length !== 0;
}

function openStory(id) {
  const story = stories.find(s => s.id === id);
  currentId = id;

  document.getElementById("category").textContent =
    story.category;

  document.getElementById("storyTitle").textContent =
    story.title;

  document.getElementById("subtitle").textContent =
    story.subtitle;

  document.getElementById("storyText").innerHTML =
    story.paragraphs.map(p => `<p>${p}</p>`).join("");

  updateSaveButton();

  reader.classList.add("show");
  document.body.style.overflow = "hidden";
}

function closeStory() {
  reader.classList.remove("show");
  document.body.style.overflow = "auto";
}

function updateSaveButton() {
  const button = document.getElementById("saveStory");

  button.textContent = saved.includes(currentId)
    ? "♥ Cerita Tersimpan"
    : "♡ Simpan Cerita";
}

function toggleSave(id) {
  if (saved.includes(id)) {
    saved = saved.filter(item => item !== id);
  } else {
    saved.push(id);
  }

  localStorage.setItem("rasyaSaved", JSON.stringify(saved));

  renderBooks();

  if (currentId === id) {
    updateSaveButton();
  }
}

bookList.addEventListener("click", function(e) {
  const saveButton = e.target.closest("[data-save]");

  if (saveButton) {
    e.stopPropagation();
    toggleSave(Number(saveButton.dataset.save));
    return;
  }

  const card = e.target.closest(".book-card");

  if (card) {
    openStory(Number(card.dataset.id));
  }
});

document.querySelectorAll(".filters button").forEach(button => {
  button.addEventListener("click", () => {
    showingSaved = false;
    category = button.dataset.category;

    document.querySelectorAll(".filters button")
      .forEach(b => b.classList.remove("active"));

    button.classList.add("active");
    renderBooks();
  });
});

search.addEventListener("input", renderBooks);

document.getElementById("closeReader")
  .addEventListener("click", closeStory);

reader.addEventListener("click", e => {
  if (e.target === reader) closeStory();
});

document.getElementById("saveStory")
  .addEventListener("click", () => {
    if (currentId !== null) toggleSave(currentId);
  });

document.getElementById("savedButton")
  .addEventListener("click", () => {
    showingSaved = !showingSaved;
    category = "Semua";
    search.value = "";

    document.querySelectorAll(".filters button")
      .forEach(b => b.classList.toggle(
        "active", b.dataset.category === "Semua"
      ));

    renderBooks();
    document.getElementById("library")
      .scrollIntoView({ behavior: "smooth" });
  });

document.addEventListener("keydown", e => {
  if (e.key === "Escape") closeStory();
});

renderBooks();
                       
